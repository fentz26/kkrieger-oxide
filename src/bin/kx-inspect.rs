use kkrieger_oxide::kx::{Document, Layout};

fn main() {
    if let Err(e) = run() {
        eprintln!("{e}");
        std::process::exit(1);
    }
}
fn run() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    let path = args
        .next()
        .unwrap_or_else(|| "assets/kkrieger3383.kx".into());
    let options: Vec<_> = args.collect();
    let beta = options.iter().any(|a| a == "--beta");
    let bytes = std::fs::read(&path)?;
    let doc = if beta {
        Document::parse_layout(&bytes, Layout::Beta2004)?
    } else {
        Document::parse(&bytes)?
    };
    if let Some(root) = options.iter().find_map(|a| a.strip_prefix("--world=")) {
        let root = root.parse()?;
        let world = kkrieger_oxide::collision::world::World::from_document(&doc, root)?;
        let faces: usize = world.faces.iter().flatten().map(Vec::len).sum();
        let events = world
            .entries
            .iter()
            .flat_map(|e| &e.events)
            .flatten()
            .count();
        println!(
            "collision world {root}: {} cells / {} adds / {} subs / {} zones / {faces} faces / {events} event records",
            world.entries.len(),
            world.adds.len(),
            world.subs.len(),
            world.zones.len()
        );
        return Ok(());
    }
    if options.iter().any(|a| a == "--animation-fixture") {
        return animation_fixture(&doc);
    }
    if let Some(root) = options.iter().find_map(|a| a.strip_prefix("--texture=")) {
        use std::io::Write;
        let root = root.parse()?;
        let image = kkrieger_oxide::texture::generate(&doc, root, 0)?;
        let mut output = std::io::BufWriter::new(std::io::stdout().lock());
        write!(output, "P6\n{} {}\n255\n", image.width, image.height)?;
        for rgba in image.rgba8().as_chunks::<4>().0 {
            output.write_all(&rgba[..3])?;
        }
        output.flush()?;
        return Ok(());
    }
    if options.iter().any(|a| a == "--textures") {
        let mut roots = std::collections::BTreeSet::new();
        for op in &doc.operators {
            if kkrieger_oxide::texture::implemented(doc.classes[op.class].id) {
                continue;
            }
            for &i in op.inputs.iter().chain(op.links.iter().flatten()) {
                if kkrieger_oxide::texture::implemented(doc.classes[doc.operators[i].class].id) {
                    roots.insert(i);
                }
            }
        }
        let roots: Vec<_> = roots.into_iter().collect();
        let start = std::time::Instant::now();
        let images = kkrieger_oxide::texture::generate_many(&doc, &roots, 0)?;
        let mut bytes = 0;
        for (&id, image) in roots.iter().zip(&images) {
            let hash = image
                .pixels
                .iter()
                .flatten()
                .fold(0xcbf29ce484222325_u64, |h, &w| {
                    w.to_le_bytes()
                        .iter()
                        .fold(h, |h, &b| (h ^ b as u64).wrapping_mul(0x100000001b3))
                });
            println!("{id:5} {}x{} {hash:016x}", image.width, image.height);
            bytes += image.pixels.len() * 8;
        }
        println!(
            "{} original texture outputs / {} generated bytes / {:?}",
            images.len(),
            bytes,
            start.elapsed()
        );
        return Ok(());
    }
    println!("{path}: {} bytes / {:?}", bytes.len(), doc.layout);
    println!(
        "{} operators / {} classes / {} events / {} splines",
        doc.operators.len(),
        doc.classes.len(),
        doc.events.len(),
        doc.splines.len()
    );
    println!(
        "song {} bytes / samples {} bytes / BPM {:.2}",
        doc.song.len(),
        doc.samples.len(),
        doc.bpm as f32 / 65536.
    );
    println!(
        "{} animated operators",
        doc.operators.iter().filter(|o| o.animation != [1]).count()
    );
    for (slot, root) in doc.roots.iter().enumerate() {
        if let Some(root) = root {
            println!(
                "root {slot}: op {root} / {} reachable / {} initialization nodes",
                doc.reachable(*root)?.len(),
                doc.initialization_order(*root)?.len()
            );
        }
    }
    println!("\nID    COUNT  PACKING");
    for (id, count) in doc.histogram() {
        let c = doc.classes.iter().find(|c| c.id == id).unwrap();
        println!(
            "{id:04x}  {count:5}  {}",
            String::from_utf8_lossy(c.packing)
        );
    }
    Ok(())
}

fn animation_fixture(doc: &Document<'_>) -> Result<(), Box<dyn std::error::Error>> {
    use std::io::Write;
    let mut out = std::io::BufWriter::new(std::io::stdout().lock());
    fn word(out: &mut impl Write, value: u32) -> std::io::Result<()> {
        out.write_all(&value.to_le_bytes())
    }
    word(&mut out, doc.splines.len() as u32)?;
    for s in &doc.splines {
        word(&mut out, s.interpolation as u32)?;
        word(&mut out, s.channels.len() as u32)?;
        for channel in &s.channels {
            word(&mut out, channel.len() as u32)?;
            for k in channel {
                word(&mut out, k.time.to_bits())?;
                word(&mut out, k.value.to_bits())?;
            }
        }
    }
    word(
        &mut out,
        doc.operators.iter().filter(|o| o.animation != [1]).count() as u32,
    )?;
    for (i, op) in doc
        .operators
        .iter()
        .enumerate()
        .filter(|(_, o)| o.animation != [1])
    {
        word(&mut out, i as u32)?;
        word(&mut out, op.parameters.len() as u32)?;
        for &w in &op.parameters {
            word(&mut out, w)?;
        }
        word(&mut out, op.animation.len() as u32)?;
        out.write_all(op.animation)?;
    }
    out.flush()?;
    Ok(())
}
